def load_en() -> dict[str, str]:
    src = (ROOT / "scripts/generate_translation_catalog.py").read_text(encoding="utf-8")
    m = re.search(r"EN: dict\[str, str\] = (\{.*?\n\})\n", src, re.DOTALL)
    return ast.literal_eval(m.group(1))


def load_msgids() -> list[str]:
    text = (ROOT / "locale/en/LC_MESSAGES/django.po").read_text(encoding="utf-8")
    entries = parse_po(text)
    msgids = [e.msgid for e in entries]
    js_msgids = []
    for line in (ROOT / "core/js_i18n.py").read_text().splitlines():
        m = re.search(r',\s*"((?:[^"\\]|\\.)*)"\s*\)', line)
        if m and "def " not in line and "return" not in line:
            js_msgids.append(m.group(1))
    return list(dict.fromkeys(msgids + [j for j in js_msgids if j not in msgids]))


def escape_py(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


def render_catalog(translations: dict[str, dict[str, str]]) -> str:
    parts = [
        '"""',
        "Katalog překladů UI řetězců (český msgid → překlady).",
        "Používá se příkazem build_locales pro doplnění .po souborů.",
        '"""',
        "",
        "# fmt: off",
        "TRANSLATIONS: dict[str, dict[str, str]] = {",
    ]
    for lang in ("en", "de", "sk", "pl", "es", "fr", "it", "nl", "pt", "ru", "uk"):
        parts.append(f'    "{lang}": {{')
        for k, v in translations[lang].items():
            parts.append(f'        "{escape_py(k)}": "{escape_py(v)}",')
        parts.append("    },")
    parts.append("}")
    parts.append("# fmt: on")
    parts.append("")
    return "\n".join(parts)


