def supplement_for(lang: str) -> dict[str, str]:
    """Sestaví doplňkový katalog pro jazyk (kromě češtiny)."""
    if lang == "cs":
        return {}
    result: dict[str, str] = {}
    catalog = TRANSLATIONS.get(lang, {})
    for msgid, translations in MULTILANG.items():
        if lang in translations:
            result[msgid] = translations[lang]
        elif msgid in catalog:
            result[msgid] = catalog[msgid]
    return result


SUPPLEMENT: dict[str, dict[str, str]] = {
    lang: supplement_for(lang)
    for lang in SYSTEM_LANGUAGE_CODES
    if lang != "cs"
}
