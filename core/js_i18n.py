def get_js_locale() -> str:
    """BCP 47 locale pro toLocaleString (cs-CZ, en-US, …)."""
    lang = get_language() or "cs"
    mapping = {
        "cs": "cs-CZ",
        "sk": "sk-SK",
        "de": "de-DE",
        "pl": "pl-PL",
        "en": "en-US",
        "es": "es-ES",
        "fr": "fr-FR",
        "it": "it-IT",
        "nl": "nl-NL",
        "pt": "pt-PT",
        "ru": "ru-RU",
        "uk": "uk-UA",
    }
    return mapping.get(lang, lang)
